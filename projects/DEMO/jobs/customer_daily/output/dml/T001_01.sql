MERGE INTO CUSTOMER_DIM t
USING (SELECT customer_id AS CUSTOMER_ID, upper(name) AS NAME_UPPER, COALESCE(country, 'UNKNOWN') AS COUNTRY FROM raw_customer WHERE deleted_flag = 0) s
ON (t.CUSTOMER_ID = s.CUSTOMER_ID)
WHEN MATCHED THEN UPDATE SET t.NAME_UPPER = s.NAME_UPPER, t.COUNTRY = s.COUNTRY
WHEN NOT MATCHED THEN INSERT (CUSTOMER_ID, NAME_UPPER, COUNTRY)
VALUES (s.CUSTOMER_ID, s.NAME_UPPER, s.COUNTRY)
